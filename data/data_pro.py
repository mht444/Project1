import pandas as pd

# 读取原始数据
df = pd.read_csv('data.csv',encoding="gbk",
                 names=['唯一标识', '所在区域', '景点名称', '评论数量', '评分', '是否为广西内容', '是否被推荐', '城市名称', '图片', '与市中心的距离', '标签',
                        '详情页链接', '市场票价', '优惠价格', '优惠描述', '实际票价', '价格类型', '价格类型描述', '是否免费',
                        '经度', '纬度', '热度评分', '省份'])

# 去重：根据“唯一标识”列去除重复数据
df = df.drop_duplicates(subset=['唯一标识'])

# 城市分组 → 省份 映射
CITY_TO_PROVINCE = {
    '北京': '北京', '天津': '天津', '上海': '上海', '重庆': '重庆',
    '石家庄': '河北', '太原': '山西', '呼和浩特': '内蒙古', '沈阳': '辽宁',
    '长春': '吉林', '哈尔滨': '黑龙江', '南京': '江苏', '杭州': '浙江',
    '合肥': '安徽', '福州': '福建', '厦门': '福建', '南昌': '江西',
    '济南': '山东', '郑州': '河南', '武汉': '湖北', '长沙': '湖南',
    '广州': '广东', '汕头': '广东', '南宁': '广西', '海口': '海南',
    '成都': '四川', '贵阳': '贵州', '昆明': '云南', '丽江': '云南',
    '拉萨': '西藏', '西安': '陕西', '兰州': '甘肃', '西宁': '青海',
    '银川': '宁夏', '乌鲁木齐': '新疆', '台北': '台湾', '香港': '香港',
    '澳门': '澳门',
}

# 省份列修正：将城市名转换为中国地图可识别的省份名
df['省份'] = df['省份'].map(CITY_TO_PROVINCE).fillna(df['省份'])

# 缺失值填充：评分列填充为0
df['评分'] = df['评分'].fillna(0)

# 标签列清洗：去除多余的符号
df['标签'] = df['标签'].str.replace('[', '').str.replace(']', '').str.replace("'", '')

# 缺失值填充：热度评分列填充为0
df['热度评分'] = df['热度评分'].fillna(0)

# 缺失值填充：评论数量列填充为0
df['评论数量'] = df['评论数量'].fillna(0)

# 保存处理后的数据到新文件
df.to_csv('data_pro.csv', index=False)